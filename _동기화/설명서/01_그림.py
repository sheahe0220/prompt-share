def 글(d, xy, t, n=24, c=진회색, 굵게=False, anchor="la"):
    """Malgun Gothic lacks some symbols (they print as boxes); draw those with Segoe UI Symbol."""
    if not any(ch in 기호 for ch in t):
        d.text(xy, t, font=F(n, 굵게), fill=c, anchor=anchor)
        return
    폭 = sum(d.textlength(ch, font=(ImageFont.truetype(기호글꼴, n) if ch in 기호 else F(n, 굵게))) for ch in t)
    x, y = xy
    if anchor[0] == "m":
        x -= 폭 / 2
    elif anchor[0] == "r":
        x -= 폭
